/**
 * Small presentational building blocks shared by every page.
 */
import { useId } from 'react';
import type { ReactNode } from 'react';
import { hrefs } from '../router';

/** Page title block. The `<h1>` receives focus after navigation (see AppShell). */
export function PageHeader({
  title,
  subtitle,
  actions,
  eyebrow,
}: {
  title: ReactNode;
  subtitle?: ReactNode;
  actions?: ReactNode;
  eyebrow?: ReactNode;
}) {
  return (
    <header className="page-header">
      <div className="page-header__text">
        {eyebrow !== undefined && <div className="page-header__eyebrow">{eyebrow}</div>}
        <h1 tabIndex={-1} data-page-title>
          {title}
        </h1>
        {subtitle !== undefined && <p className="page-header__subtitle">{subtitle}</p>}
      </div>
      {actions !== undefined && <div className="page-header__actions">{actions}</div>}
    </header>
  );
}

/** A titled content card. */
export function Card({
  title,
  description,
  actions,
  children,
  className,
  headingLevel = 2,
  id,
}: {
  title?: ReactNode;
  description?: ReactNode;
  actions?: ReactNode;
  children?: ReactNode;
  className?: string;
  headingLevel?: 2 | 3;
  id?: string;
}) {
  const Heading = headingLevel === 2 ? 'h2' : 'h3';
  return (
    <section className={`card${className ? ` ${className}` : ''}`} id={id}>
      {(title !== undefined || actions !== undefined) && (
        <div className="card__header">
          <div>
            {title !== undefined && <Heading className="card__title">{title}</Heading>}
            {description !== undefined && <p className="card__description">{description}</p>}
          </div>
          {actions !== undefined && <div className="card__actions">{actions}</div>}
        </div>
      )}
      {children}
    </section>
  );
}

/** A single headline number. */
export function KpiTile({
  label,
  value,
  unit,
  hint,
  tone,
}: {
  label: string;
  value: ReactNode;
  unit?: string;
  hint?: ReactNode;
  tone?: 'default' | 'attention';
}) {
  return (
    <div className={`kpi${tone === 'attention' ? ' kpi--attention' : ''}`}>
      <div className="kpi__label">{label}</div>
      <div className="kpi__value">
        {value}
        {unit !== undefined && unit !== '' && <span className="kpi__unit"> {unit}</span>}
      </div>
      {hint !== undefined && <div className="kpi__hint">{hint}</div>}
    </div>
  );
}

/** Small status label. */
export function Badge({ children, tone = 'neutral', title }: { children: ReactNode; tone?: 'neutral' | 'sim' | 'info' | 'warning' | 'success'; title?: string }) {
  return (
    <span className={`badge badge--${tone}`} title={title}>
      {children}
    </span>
  );
}

/** Badge shown wherever simulated data is on screen. */
export function SimulatedBadge() {
  return (
    <Badge tone="sim" title="Generated by the SurgeonPulse physiological simulator — not real participant data">
      Simulated
    </Badge>
  );
}

/** Inline message. `alert` tone is announced to screen readers. */
export function Notice({
  tone = 'info',
  title,
  children,
  onDismiss,
}: {
  tone?: 'info' | 'warning' | 'error' | 'success';
  title?: ReactNode;
  children?: ReactNode;
  onDismiss?: () => void;
}) {
  return (
    <div className={`notice notice--${tone}`} role={tone === 'error' ? 'alert' : 'status'}>
      <div className="notice__body">
        {title !== undefined && <strong className="notice__title">{title}</strong>}
        {children !== undefined && <div>{children}</div>}
      </div>
      {onDismiss !== undefined && (
        <button type="button" className="btn btn--ghost btn--small" onClick={onDismiss}>
          Dismiss
        </button>
      )}
    </div>
  );
}

/** Determinate progress bar with an accessible label. */
export function ProgressBar({ value, max, label }: { value: number; max: number; label: string }) {
  const pct = max > 0 ? Math.min(100, Math.max(0, (value / max) * 100)) : 0;
  return (
    <div className="progress">
      <div className="progress__label" aria-hidden="true">
        {label}
      </div>
      <div
        className="progress__track"
        role="progressbar"
        aria-label={label}
        aria-valuemin={0}
        aria-valuemax={max}
        aria-valuenow={value}
        aria-valuetext={`${value} of ${max}`}
      >
        <div className="progress__bar" style={{ width: `${pct}%` }} />
      </div>
    </div>
  );
}

