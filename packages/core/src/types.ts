/**
 * SurgeonPulse domain model.
 *
 * This file is the shared contract between the mobile app, the research
 * dashboard, the ingest server and the Python analysis toolkit. Changing a
 * persisted shape requires bumping SCHEMA_VERSION and adding a migration in
 * `io/schema.ts`.
 *
 * Conventions
 * - All timestamps are UTC epoch milliseconds (`EpochMs`).
 * - Heart rate is in beats per minute, RR intervals in milliseconds.
 * - Questionnaire ratings are 0–100 (NASA-TLX digital convention, step 5).
 * - Nothing in a session may directly identify a patient. Participants are
 *   identified only by a pseudonymous study code.
 */

export const SCHEMA_VERSION = 1 as const;
export type SchemaVersion = typeof SCHEMA_VERSION;

/** UTC epoch milliseconds. */
export type EpochMs = number;

// ---------------------------------------------------------------------------
// Sensors & platform
// ---------------------------------------------------------------------------

/**
 * Where heart-rate data came from.
 * - `ble`: Bluetooth LE Heart Rate Profile device (chest strap, armband, watch broadcast) via native BLE.
 * - `web-bluetooth`: same profile via the Web Bluetooth API (Chrome/Edge/Android browsers).
 * - `healthkit`: Apple Health (e.g. Apple Watch) imported for the session window.
 * - `health-connect`: Android Health Connect (Wear OS, Samsung, Fitbit, Garmin sync) imported for the session window.
 * - `simulated`: generated by the built-in physiological simulator (demo/training/testing).
 * - `import`: loaded from a file produced by another tool.
 */
export type SensorSourceKind =
  | 'ble'
  | 'web-bluetooth'
  | 'healthkit'
  | 'health-connect'
  | 'simulated'
  | 'import';

export type Platform = 'ios' | 'android' | 'web' | 'unknown';

export interface SensorInfo {
  source: SensorSourceKind;
  /** Human-readable device name, e.g. "Polar H10 A1B2C3D4". */
  name?: string;
  /** Opaque device identifier. Removed by de-identification. */
  id?: string;
  /** Body location reported by the sensor (BLE Body Sensor Location), e.g. "chest". */
  location?: string;
}

// ---------------------------------------------------------------------------
// Physiological signals
// ---------------------------------------------------------------------------

export interface HeartRateSample {
  t: EpochMs;
  /** Beats per minute (integer for BLE sources, may be fractional for imports). */
  bpm: number;
  /** Skin contact as reported by the sensor; undefined when the sensor does not support contact detection. */
  contact?: boolean;
}

/**
 * One RR (inter-beat) interval.
 *
 * `t` is the time the interval was *received* (for BLE this is the
 * notification time; several intervals delivered in one notification share
 * the same `t`). Ordering in the array is the beat order.
 */
export interface RRInterval {
  t: EpochMs;
  /** Interval between successive R-peaks in milliseconds. */
  ms: number;
}

/**
 * Pre-computed HRV value from a platform health store when raw RR intervals
 * are unavailable (Apple Health stores SDNN, Health Connect stores RMSSD).
 */
export interface ExternalHrvReading {
  t: EpochMs;
  metric: 'sdnn' | 'rmssd';
  ms: number;
  source: SensorSourceKind;
}

// ---------------------------------------------------------------------------
// Operative timeline
// ---------------------------------------------------------------------------

/**
 * Operative phases. A phase begins at its `phase` event and lasts until the
 * next phase event or the end of the session.
 */
export type PhaseKind =
  | 'pre-op' //       scrub, positioning, WHO time-out
  | 'incision' //     access / opening / port placement
  | 'dissection' //   main operative work
  | 'critical' //     critical step (e.g. critical view of safety, anastomosis, vessel ligation)
  | 'closure' //      haemostasis check, closure
  | 'post-op'; //     debrief, handover, documentation

export const PHASE_ORDER: readonly PhaseKind[] = [
  'pre-op',
  'incision',
  'dissection',
  'critical',
  'closure',
  'post-op',
] as const;

/** Instantaneous markers that can be logged at any time. */
export type MarkerKind =
  | 'complication' //  unexpected bleeding, injury, conversion, etc.
  | 'interruption' //  page, phone, door, staff change
  | 'equipment' //     instrument / device / imaging problem
  | 'teaching' //      teaching moment or trainee takes over a step
  | 'takeover' //      supervising surgeon takes over
  | 'note'; //         free-form timestamped note

export const MARKER_KINDS: readonly MarkerKind[] = [
  'complication',
  'interruption',
  'equipment',
  'teaching',
  'takeover',
  'note',
] as const;

/** Who logged an event — matters for research validity. */
export type EventLogger = 'self' | 'team' | 'retrospective';

interface SessionEventBase {
  id: string;
  t: EpochMs;
  note?: string;
  loggedBy?: EventLogger;
}

export interface PhaseEvent extends SessionEventBase {
  type: 'phase';
  phase: PhaseKind;
}

export interface MarkerEvent extends SessionEventBase {
  type: 'marker';
  marker: MarkerKind;
}

export type SessionEvent = PhaseEvent | MarkerEvent;

// ---------------------------------------------------------------------------
// Procedure, participant, self-report
// ---------------------------------------------------------------------------

export type SurgicalApproach =
  | 'open'
  | 'laparoscopic'
  | 'robotic'
  | 'endoscopic'
  | 'percutaneous'
  | 'microsurgical'
  | 'other';

export type SurgeonRole = 'primary' | 'assistant' | 'supervising' | 'observing';

export type Urgency = 'elective' | 'urgent' | 'emergency';

export interface ProcedureInfo {
  /** Procedure name — prefer a catalogue entry. Must never contain patient details. */
  name: string;
  /** Catalogue id when chosen from PROCEDURE_CATALOG. */
  catalogId?: string;
  specialty?: string;
  approach?: SurgicalApproach;
  role?: SurgeonRole;
  /** Anticipated complexity rated by the surgeon before the case, 1 (routine) – 5 (very complex). */
  complexity?: 1 | 2 | 3 | 4 | 5;
  urgency?: Urgency;
}

export type TrainingLevel =
  | 'consultant'
  | 'fellow'
  | 'registrar'
  | 'resident'
  | 'intern'
  | 'student'
  | 'other';

export interface ConsentRecord {
  /** Version string of the participant information & consent form, e.g. "PICF-1.2". */
  version: string;
  givenAt: EpochMs;
  withdrawnAt?: EpochMs;
}

export interface ParticipantProfile {
  /** Pseudonymous study code, e.g. "SP-014". Never a name, email or employee id. */
  code: string;
  trainingLevel?: TrainingLevel;
  specialty?: string;
  yearsExperience?: number;
  /** Birth year only (not full date) to limit identifiability; used for age-predicted max HR. */
  birthYear?: number;
  /** Measured maximum heart rate override (bpm). */
  maxHr?: number;
  /** Typical resting heart rate (bpm) when no session baseline is recorded. */
  restingHr?: number;
  consent?: ConsentRecord;
}

/** Snapshot of profile fields stored with each session so sessions are self-describing. */
export type ParticipantSnapshot = Pick<
  ParticipantProfile,
  'trainingLevel' | 'specialty' | 'yearsExperience' | 'birthYear' | 'maxHr' | 'restingHr'
>;

export type WorkloadInstrument = 'surg-tlx' | 'nasa-tlx';

/** SURG-TLX dimensions (Wilson et al., 2011). */
export type SurgTlxDimension =
  | 'mental'
  | 'physical'
  | 'temporal'
  | 'complexity'
  | 'stress'
  | 'distraction';

/** NASA-TLX dimensions (Hart & Staveland, 1988). */
export type NasaTlxDimension =
  | 'mental'
  | 'physical'
  | 'temporal'
  | 'performance'
  | 'effort'
  | 'frustration';

export interface SurgTlxResponse {
  instrument: 'surg-tlx';
  /** Each rating 0–100. */
  ratings: Record<SurgTlxDimension, number>;
  /** Optional pairwise-comparison tallies (each 0–5, summing to 15). */
  weights?: Record<SurgTlxDimension, number>;
  completedAt: EpochMs;
}

export interface NasaTlxResponse {
  instrument: 'nasa-tlx';
  /** Each rating 0–100. For `performance`, 0 = perfect, 100 = failure (standard NASA-TLX anchor). */
  ratings: Record<NasaTlxDimension, number>;
  weights?: Record<NasaTlxDimension, number>;
  completedAt: EpochMs;
}

export type WorkloadResponse = SurgTlxResponse | NasaTlxResponse;

export type CaseOutcome = 'as-planned' | 'minor-deviation' | 'major-deviation';

export interface PostOpReport {
  workload?: WorkloadResponse;
  /** Self-rated performance, 0 (very poor) – 10 (excellent). */
  performance?: number;
  /** Overall perceived stress during the case, 0 (none) – 10 (extreme). */
  perceivedStress?: number;
  /** Hours slept the night before. */
  sleepHours?: number;
  /** Caffeine within 2 hours before the case. */
  caffeine?: boolean;
  outcome?: CaseOutcome;
  /** Free text. Removed by de-identification by default. */
  notes?: string;
}

/** Resting reference measured before the case (or entered manually). */
export interface Baseline {
  startedAt: EpochMs;
  endedAt: EpochMs;
  /** Mean resting heart rate, bpm. */
  restingHr: number;
  rmssd?: number;
  sdnn?: number;
  source: 'measured' | 'manual' | 'profile';
}

// ---------------------------------------------------------------------------
// Session
// ---------------------------------------------------------------------------

export type SessionStatus = 'recording' | 'completed' | 'aborted';

export interface AppInfo {
  version: string;
  platform: Platform;
}

export interface SurgicalSession {
  schemaVersion: SchemaVersion;
  id: string;
  participantCode: string;
  procedure: ProcedureInfo;
  startedAt: EpochMs;
  /** Undefined while recording. */
  endedAt?: EpochMs;
  status: SessionStatus;
  sensor: SensorInfo;
  app: AppInfo;
  /** Local timezone offset in minutes east of UTC at start (e.g. AEST = 600). Allows time-of-day analysis. */
  tzOffsetMin?: number;
  participantSnapshot?: ParticipantSnapshot;
  baseline?: Baseline;
  /** Sorted ascending by `t`. */
  samples: HeartRateSample[];
  /** Beat order (ascending `t`, ties allowed). */
  rr: RRInterval[];
  externalHrv?: ExternalHrvReading[];
  /** Sorted ascending by `t`. */
  events: SessionEvent[];
  postOp?: PostOpReport;
  tags?: string[];
}

/** File format produced by every export path (mobile share sheet, server export). */
export interface ExportBundle {
  format: 'surgeonpulse-export';
  version: 1;
  exportedAt: EpochMs;
  app?: AppInfo;
  /** True when `deidentifySession` was applied to every session. */
  deidentified: boolean;
  participants: ParticipantProfile[];
  sessions: SurgicalSession[];
}

// ---------------------------------------------------------------------------
// Analytics outputs
// ---------------------------------------------------------------------------

export interface HrStats {
  count: number;
  mean: number;
  median: number;
  min: number;
  max: number;
  /** Sample standard deviation (n − 1); 0 when count is 1. */
  sd: number;
  /** 95th percentile (linear interpolation between closest ranks). */
  p95: number;
}

export interface HrvTimeDomain {
  /** Number of valid RR intervals used. */
  n: number;
  /** Number of valid successive-difference pairs used for RMSSD / pNN50. */
  pairs: number;
  meanRr: number;
  /** Sample SD of RR (n − 1), ms. */
  sdnn: number;
  /** Root mean square of successive differences, ms. */
  rmssd: number;
  /** Percentage (0–100) of successive differences > 50 ms. */
  pnn50: number;
  /** 60000 / meanRr. */
  meanHr: number;
}

export interface ArtifactReport {
  total: number;
  /** Intervals flagged as artefact / ectopic and excluded. */
  removed: number;
  /** removed / total (0 when total is 0). */
  ratio: number;
}

export interface ZoneDefinition {
  id: string;
  label: string;
  /** Inclusive lower bound, bpm. */
  minBpm: number;
  /** Exclusive upper bound, bpm (use Infinity for the top zone). */
  maxBpm: number;
}

export interface ZoneTime {
  id: string;
  label: string;
  seconds: number;
  /** seconds / total seconds across all zones (0 when total is 0). */
  fraction: number;
}

export interface PhaseSegment {
  phase: PhaseKind;
  /** 0-based order of the segment within the session. */
  index: number;
  start: EpochMs;
  end: EpochMs;
}

export interface PhaseSummary extends PhaseSegment {
  durationSec: number;
  hr: HrStats | null;
  hrv: HrvTimeDomain | null;
  /** hr.mean − baseline.restingHr, null if either missing. */
  meanHrDelta: number | null;
}

export interface StressEpisode {
  start: EpochMs;
  end: EpochMs;
  durationSec: number;
  peakBpm: number;
  peakT: EpochMs;
  meanBpm: number;
  /** Phase in progress at `peakT`. */
  phase?: PhaseKind;
  /** Ids of events within [start − 2 min, end]. */
  relatedEventIds: string[];
}

export interface DataQuality {
  /** Fraction (0–1) of session duration covered by HR samples (gaps > maxGap excluded). */
  coverage: number;
  gapCount: number;
  longestGapSec: number;
  /** RR artefact ratio, null when no RR data. */
  rrArtifactRatio: number | null;
  /** Mean HR sample rate over covered time, Hz. */
  sampleRateHz: number;
}

export interface WorkloadScore {
  instrument: WorkloadInstrument;
  /** Unweighted mean of the six ratings (0–100). */
  raw: number;
  /** Weighted score Σ(rating × weight) / 15, null when weights absent/invalid. */
  weighted: number | null;
  dimensions: Record<string, number>;
}

export interface SessionSummary {
  sessionId: string;
  participantCode: string;
  procedureName: string;
  specialty?: string;
  approach?: SurgicalApproach;
  role?: SurgeonRole;
  urgency?: Urgency;
  complexity?: number;
  trainingLevel?: TrainingLevel;
  startedAt: EpochMs;
  endedAt: EpochMs;
  durationSec: number;
  hr: HrStats | null;
  hrv: HrvTimeDomain | null;
  rrArtifacts: ArtifactReport | null;
  /**
   * Baevsky stress index: median over 5-min windows with ≥ 4 min of clean beats (comparable across case lengths);
   * null without sufficient RR data or when more than 10 % of RR intervals were artefacts.
   */
  stressIndex: number | null;
  baseline: Baseline | null;
  /** hr.mean − baseline.restingHr. */
  meanHrDelta: number | null;
  /** Robust peak HR (`peakHr`, highest 11-s rolling median) − baseline.restingHr. */
  peakHrDelta: number | null;
  maxHr: number | null;
  zones: ZoneTime[];
  /** Fraction of time at or above 70 % of max HR (0–1), null when max HR unknown. */
  highIntensityFraction: number | null;
  phases: PhaseSummary[];
  episodes: StressEpisode[];
  markerCounts: Partial<Record<MarkerKind, number>>;
  workload: WorkloadScore | null;
  performance: number | null;
  perceivedStress: number | null;
  quality: DataQuality;
  // Provenance and covariates. Optional only so summaries stored by older versions still type-check;
  // `summarizeSession` always sets every key below except `tzOffsetMin` (omitted when the session has none).
  /**
   * Robust peak heart rate (bpm): the highest 11-s rolling median of the valid samples, so a single spike
   * (e.g. diathermy interference) does not become the peak. `hr.max` stays the raw maximum.
   */
  peakHr?: number | null;
  /** `session.sensor.source`. */
  sensorSource?: SensorSourceKind;
  /** True for synthetic data: sensor source `simulated`, or a `simulated` / `demo` tag. */
  simulated?: boolean;
  /** `session.tzOffsetMin` (minutes east of UTC at the start), omitted when unknown. */
  tzOffsetMin?: number;
  /** Debrief covariates from `postOp`, null when not answered. */
  sleepHours?: number | null;
  caffeine?: boolean | null;
  outcome?: CaseOutcome | null;
  /** Largest sample spacing treated as continuous for coverage, zone dwell and episodes (ms). */
  maxGapMs?: number;
  /** {@link ANALYTICS_VERSION} of the code that computed this summary. */
  analyticsVersion?: string;
}

/**
 * Version of the summary definitions (metrics, quality rules, episode rules). Bumped whenever a change would give a
 * different `SessionSummary` for the same session, so stored summaries computed by older code can be recognised
 * and recomputed (and research exports can say which definitions produced each row).
 */
export const ANALYTICS_VERSION = '2';

/** Feedback message for the surgeon (shown in the app's Insights tab). */
export interface Insight {
  id: string;
  kind: 'info' | 'positive' | 'attention';
  title: string;
  detail: string;
  /** Session ids that support this insight. */
  evidence: string[];
}
